function main() {
  const existing = JSON.parse(fs.readFileSync(THEMES_PATH, 'utf8'));
  const flagshipNames = ['Sakura Midnight', 'WLOP Cosmic', 'Midnight Obsidian'];
  const nextThemes = {};

  for (const name of flagshipNames) {
    if (existing[name]) {
      nextThemes[name] = existing[name];
    }
  }

  let lightCount = 0;
  let darkCount = Object.keys(nextThemes).length;

  for (const [name, spec] of Object.entries(ICONIC_THEMES)) {
    const built = buildGlassTheme(spec);
    const check = validateThemePreset(name, built);
    if (!check.valid) {
      throw new Error(`Validation failed for "${name}": ${check.errors.join('; ')}`);
    }
    nextThemes[name] = built;
    if (built.isLight) lightCount += 1;
    else darkCount += 1;
  }

  fs.writeFileSync(THEMES_PATH, JSON.stringify(nextThemes, null, 2) + '\n', 'utf8');
  console.log(
    `[generate-themes] Wrote ${Object.keys(nextThemes).length} themes (${darkCount} dark, ${lightCount} light) to ${THEMES_PATH}`
  );
}

main();
