function hexToRgb(hex) {
  const clean = String(hex).replace('#', '').trim();
  const full = clean.length === 3 ? clean.split('').map((c) => c + c).join('') : clean;
  const n = Number.parseInt(full, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

function rgbStr(hex) {
  const [r, g, b] = hexToRgb(hex);
  return `${r}, ${g}, ${b}`;
}

function rgba(hex, alpha) {
  const [r, g, b] = hexToRgb(hex);
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}

function mixHex(hexA, hexB, weightB = 0.5) {
  const a = hexToRgb(hexA);
  const b = hexToRgb(hexB);
  const m = a.map((v, i) => Math.round(v * (1 - weightB) + b[i] * weightB));
  return '#' + m.map((v) => v.toString(16).padStart(2, '0')).join('');
}

function buildGlassTheme(spec) {
  const {
    concept,
    bg,
    surface,
    primary,
    secondary,
    text,
    muted,
    success,
    warning,
    error,
    info,
    isLight = false,
    cornerSvg = '',
    glowAngle = '145deg',
  } = spec;

  const deepest = isLight ? mixHex(bg, '#d8dee9', 0.16) : mixHex(bg, '#000000', 0.34);
  const raised = isLight ? mixHex(surface, '#ffffff', 0.45) : mixHex(surface, '#ffffff', 0.06);
  const codeBg = isLight ? mixHex(bg, '#000000', 0.04) : mixHex(bg, '#000000', 0.24);
  const terminalBg = isLight ? mixHex(bg, '#000000', 0.03) : mixHex(bg, '#000000', 0.32);
  const secondaryText = muted || (isLight ? mixHex(text, '#64748b', 0.35) : mixHex(text, bg, 0.28));
  const mutedText = isLight ? mixHex(text, '#64748b', 0.52) : mixHex(text, bg, 0.44);

  const userBubbleStart = isLight ? mixHex(surface, primary, 0.14) : mixHex(surface, primary, 0.24);
  const userBubbleEnd = isLight ? mixHex(bg, secondary, 0.12) : mixHex(bg, secondary, 0.16);

  const pureBg = isLight
    ? `radial-gradient(circle at 78% 18%, ${rgba(primary, 0.16)} 0%, transparent 52%), radial-gradient(circle at 18% 82%, ${rgba(secondary, 0.14)} 0%, transparent 50%), linear-gradient(160deg, ${bg} 0%, ${deepest} 100%)`
    : `radial-gradient(circle at 76% 22%, ${rgba(primary, 0.22)} 0%, transparent 54%), radial-gradient(circle at 18% 82%, ${rgba(secondary, 0.16)} 0%, transparent 50%), linear-gradient(160deg, ${bg} 0%, ${deepest} 100%)`;

  const preset = {
    concept,
    refinedSurfaceTokens: true,
    primary,
    secondary,
    glow: rgba(primary, isLight ? 0.22 : 0.26),
    secondaryGlow: rgba(secondary, isLight ? 0.18 : 0.2),
    bg: `linear-gradient(${glowAngle}, ${rgba(userBubbleStart, isLight ? 0.92 : 0.92)} 0%, ${rgba(userBubbleEnd, isLight ? 0.95 : 0.96)} 100%)`,
    frameBg: `linear-gradient(135deg, ${rgba(primary, isLight ? 0.72 : 0.74)} 0%, ${rgba(secondary, isLight ? 0.52 : 0.54)} 55%, ${rgba(primary, 0.58)} 100%)`,
    textColor: text,
    borderColor: rgba(primary, isLight ? 0.28 : 0.3),
    innerBorder: `1px solid ${rgba(text, isLight ? 0.14 : 0.1)}`,
    clearBackdrop: true,
    overlayRgb: rgbStr(bg),
    focusVignetteRgb: rgbStr(deepest),
    defaultDimming: isLight ? 24 : 38,
    bgPosition: 'center center',
    pureBg,
    wallpaper: '',
    surfaceBg: surface,
    surfaceRaisedBg: raised,
    sidebarBg: rgba(isLight ? surface : deepest, isLight ? 0.84 : 0.72),
    sidebarBlur: '2px',
    sidebarHoverBg: rgba(primary, isLight ? 0.12 : 0.13),
    sidebarActiveBg: rgba(primary, isLight ? 0.18 : 0.2),
    sidebarEnhanceText: !isLight,
    aiCardBg: rgba(isLight ? '#ffffff' : surface, isLight ? 0.92 : 0.92),
    aiCardBorder: rgba(primary, isLight ? 0.2 : 0.18),
    codeBg,
    codeHeaderBg: rgba(surface, 0.94),
    inlineCodeBg: rgba(isLight ? primary : raised, isLight ? 0.12 : 0.88),
    inlineCodeColor: isLight ? mixHex(primary, '#0f172a', 0.22) : mixHex(primary, '#ffffff', 0.28),
    terminalBg,
    terminalFg: text,
    terminalCursor: primary,
    terminalSelection: rgba(primary, 0.28),
    headerBg: rgba(isLight ? surface : deepest, isLight ? 0.84 : 0.72),
    headerBlur: '2px',
    headerBorder: rgba(primary, isLight ? 0.16 : 0.14),
    unifiedGlass: true,
    btnBg: rgba(isLight ? '#ffffff' : raised, isLight ? 0.86 : 0.72),
    inputGlassBg: rgba(surface, isLight ? 0.88 : 0.82),
    inputCardBg: `linear-gradient(145deg, ${rgba(isLight ? '#ffffff' : surface, 0.95)} 0%, ${rgba(bg, 0.97)} 100%)`,
    modalBg: rgba(isLight ? '#ffffff' : deepest, 0.97),
    modalHeaderBg: rgba(surface, 0.94),
    popupBg: rgba(isLight ? '#ffffff' : surface, 0.97),
    popupBorder: rgba(primary, isLight ? 0.24 : 0.24),
    cardBg: rgba(isLight ? '#ffffff' : surface, isLight ? 0.86 : 0.86),
    cardSelectedBg: rgba(primary, isLight ? 0.16 : 0.24),
    isOrnament: Boolean(cornerSvg),
    ...(cornerSvg ? { cornerSvg } : {}),
    sticker: '',
    stickerW: 0,
    stickerH: 0,
    stickerTop: 0,
    stickerRight: 0,
    isLight,
    uiTextColor: text,
    uiSecondaryColor: secondaryText,
    uiMutedColor: mutedText,
    successColor: success,
    warningColor: warning,
    errorColor: error,
    infoColor: info || secondary,
    diffAddedBg: rgba(success, isLight ? 0.14 : 0.12),
    diffAddedTextBg: rgba(success, isLight ? 0.24 : 0.24),
    diffRemovedBg: rgba(error, isLight ? 0.14 : 0.13),
    diffRemovedTextBg: rgba(error, isLight ? 0.24 : 0.25),
    diffModifiedBg: rgba(warning, isLight ? 0.14 : 0.12),
    pillBg: rgba(isLight ? '#ffffff' : surface, isLight ? 0.9 : 0.88),
    pillHoverBg: rgba(isLight ? surface : raised, 0.96),
    pillTextColor: text,
    pillBorder: rgba(primary, isLight ? 0.26 : 0.24),
  };

  return preset;
}

